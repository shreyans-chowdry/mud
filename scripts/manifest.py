#!/usr/bin/env python3
"""Build source manifest, complete file-content bundle and distributable zip without runtime state."""
import hashlib
import json
import os
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {'node_modules', '.venv', '__pycache__', '.pytest_cache', '.ruff_cache', '.next', 'runtime', 'coverage',
        'htmlcov', 'artifacts', 'cache', 'test-results', 'playwright-report', '.git'}
EXCLUDE = {'.env', '.env.local', '.coverage', '.DS_Store', 'coverage.json', 'tsconfig.tsbuildinfo', 'docs/MANIFEST.md'}


def files():
    selected = []
    for directory, dirs, names in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP and not d.endswith('.egg-info')]
        for name in names:
            path = Path(directory) / name
            rel = path.relative_to(ROOT).as_posix()
            if name.startswith('.env') and not (name.endswith('.example') or name == '.env.example'):
                continue
            if (rel.startswith('deployments/') and name.endswith('.json')) or rel == 'frontend/public/deployment.json' or (rel.startswith('config/eligibility') and name.endswith('.json')):
                continue
            if rel not in EXCLUDE and name not in EXCLUDE and path.suffix not in {'.pyc', '.db'}:
                selected.append(path)
    return sorted(selected)


def dependencies(path):
    suffix, text = path.suffix, path.read_text(errors='replace')
    if suffix == '.sol':
        return re.findall(r'import\s+(?:[^;]*?from\s+)?["\']([^"\']+)', text)
    if suffix in {'.ts', '.tsx', '.js', '.cjs', '.mjs'}:
        return sorted(set(re.findall(r'(?:from\s+|require\()["\']([^"\']+)', text)))
    if suffix == '.py':
        return sorted(set(re.findall(r'^from\s+([.\w]+)\s+import', text, re.M)))
    return []


def main():
    source = files()
    lines = ['# File manifest and dependency index', '',
             'Generated by `python3 scripts/manifest.py`. Paths are relative to repository root. Every source/configuration file is included; installed dependencies, credentials, build caches and live databases are excluded. The manifest excludes its own digest to avoid recursive hashing.', '',
             '| File | SHA-256 | Direct imports (packages or relative modules) |', '|---|---|---|']
    for p in source:
        rel = p.relative_to(ROOT).as_posix()
        lines.append(f'| `{rel}` | `{hashlib.sha256(p.read_bytes()).hexdigest()}` | '+', '.join(f'`{x}`' for x in dependencies(p))+' |')
    manifest = ROOT / 'docs/MANIFEST.md'
    manifest.write_text('\n'.join(lines)+'\n')
    source.append(manifest)
    output = ROOT.parent
    bundle = output / 'mud-protocol-sources.md'
    with bundle.open('w') as f:
        f.write('# MUD Protocol — complete source files\n\nEach heading is an exact repository path, followed by its complete contents. See docs/VERIFICATION.md for evidence and limitations.\n\n')
        for p in sorted(source):
            text = p.read_text()
            fence = '`'*(max([len(m.group(0)) for m in re.finditer(r'`{3,}', text)] or [2])+1)
            f.write(f'## mud-protocol/{p.relative_to(ROOT).as_posix()}\n\n{fence}\n{text}')
            if not text.endswith('\n'):
                f.write('\n')
            f.write(f'{fence}\n\n')
    archive = output / 'mud-protocol.zip'
    with zipfile.ZipFile(archive, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(source):
            z.write(p, arcname='mud-protocol/'+p.relative_to(ROOT).as_posix())
    print(json.dumps({'files': len(source), 'archive': str(archive), 'complete_source_bundle': str(bundle),
                      'archive_sha256': hashlib.sha256(archive.read_bytes()).hexdigest()}))


if __name__ == '__main__':
    main()
