const fs = require('node:fs');
const path = require('node:path');
const names = ['MudTokenAMM','MudAirdrop','MudMarketplace','MudTreasury','MudPriceOracle','MudProtocolConfig'];
fs.mkdirSync('abi', {recursive:true});
for (const name of names) {
 const artifact = JSON.parse(fs.readFileSync(path.join('contracts/artifacts/contracts/src', `${name}.sol`, `${name}.json`)));
 fs.writeFileSync(`abi/${name}.json`, JSON.stringify(artifact.abi, null, 2)+'\n');
}
fs.writeFileSync('frontend/lib/abi.ts', '// Generated by npm run compile. ABI v1.\n'+names.map(n => `export const ${n}Abi = ${fs.readFileSync(`abi/${n}.json`, 'utf8').trim()} as const;`).join('\n')+'\n');
